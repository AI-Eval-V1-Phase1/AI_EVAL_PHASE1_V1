import express from "express";
import authenticateToken from "../middlewares/routesProtection.js";
import submitBuyerCotsAssessment from "../controllers/assessments/submitBuyerCots.controller.js";
import saveBuyerCotsDraft from "../controllers/assessments/saveBuyerCotsDraft.controller.js";
import getBuyerCotsById from "../controllers/assessments/getBuyerCotsById.controller.js";
import deleteAssessment from "../controllers/assessments/deleteAssessment.controller.js";
import submitVendorCotsAssessment from "../controllers/assessments/submitVendorCots.controller.js";
import saveVendorCotsDraft from "../controllers/assessments/saveVendorCotsDraft.controller.js";
import getVendorCotsById from "../controllers/assessments/getVendorCotsById.controller.js";
import getBuyerCotsAutoGenerated from "../controllers/assessments/getBuyerCotsAutoGenerated.controller.js";
import listAssessmentsByOrganization from "../controllers/assessments/listAssessmentsByOrganization.controller.js";
import listCustomerRiskReports from "../controllers/assessments/listCustomerRiskReports.controller.js";
import getCustomerRiskReportById from "../controllers/assessments/getCustomerRiskReportById.controller.js";

const assessmentRouter = express.Router();

assessmentRouter
.get("/assessments", authenticateToken, listAssessmentsByOrganization)
.get("/customerRiskReports", authenticateToken, listCustomerRiskReports)
.get("/customerRiskReports/:id", authenticateToken, getCustomerRiskReportById)
.get("/buyerCotsAssessment/:id", authenticateToken, getBuyerCotsById)
.get("/vendorCotsAssessment/:id", authenticateToken, getVendorCotsById)
.post("/buyerCotsAssessment/autoGenerated", authenticateToken, getBuyerCotsAutoGenerated)
.post("/buyerCotsAssessment/save-draft", authenticateToken, saveBuyerCotsDraft)
.post("/buyerCotsAssessment", authenticateToken, submitBuyerCotsAssessment)
.post("/vendorCotsAssessment/save-draft", authenticateToken, saveVendorCotsDraft)
.post("/vendorCotsAssessment", authenticateToken, submitVendorCotsAssessment)
.delete("/assessments/:id", authenticateToken, deleteAssessment);


export default assessmentRouter;
