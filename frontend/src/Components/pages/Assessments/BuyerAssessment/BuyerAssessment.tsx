import "../../VendorOnboarding/vendor_onboarding.css";
import "../../BuyerOnboarding/buyer_onboarding.css";
import CardContainerOnBoarding from "../../../UI/CardContainerOnBoarding";
import CardOnBoarding from "../../../UI/CardOnBoarding";
import OrganizationProfile from "./OrganizationProfile";

import { BUYER_COTS_INITIAL_STATE } from "../../../../constants/buyerCotsAssessmentKeys";
import {
  BUYER_COTS_READONLY_KEYS,
  mapOnboardingToAssessmentForm,
} from "../../../../constants/buyerCotsOnboardingMapping";
import { useState, useEffect, useRef } from "react";
import { useNavigate } from "react-router-dom";
import Button from "../../../UI/Button";
import { ChevronLeftCircle, ChevronRightCircle, Send } from "lucide-react";
import CardConfirmation from "../../../UI/CardConfirmation";
import UseCase from "./UseCase";
import VendorEvaluation from "./VendorEvaluation";
import Readiness from "./Readiness";
import RiskProfile from "./RiskProfile";
import VendoeRisk from "./VendorRisk";
import Implementation from "./Implementation";
import Evidence from "./Evidence";
import AutoGenerated from "./AutoGenerated";
import StepBuyerCotsPreview from "./StepBuyerCotsPreview";
import { BUYER_COTS_ASSESSMENT } from "../../../../constants/buyerCOTSData 1";

const BASE_URL = import.meta.env.VITE_BASE_URL;

const AUTO_GENERATED_KEYS = [
  "identifiedRisks",
  "riskDomainScores",
  "contextualMultipliers",
  "riskMitigation",
];

/** Form keys that store multiselect as JSON strings; send as parsed arrays for jsonb columns */
const MULTISELECT_JSON_KEYS = [
  "integrationSystems",
  "techStack",
  "implementationTeamComposition",
  "regulatoryRequirements",
  "impactedStakeholders",
  "vendorCertifications",
] as const;

function prepareSubmitPayload(
  data: Record<string, string>,
  riskMitigationMappingIds: number[]
): Record<string, unknown> {
  const out: Record<string, unknown> = { ...data };
  for (const key of MULTISELECT_JSON_KEYS) {
    const v = out[key];
    if (typeof v === "string" && v.trim().length > 0) {
      try {
        const parsed = JSON.parse(v);
        if (Array.isArray(parsed)) out[key] = parsed;
      } catch {
        // leave as string if not valid JSON
      }
    }
  }
  if (riskMitigationMappingIds.length > 0) {
    out.riskMitigationMappingIds = riskMitigationMappingIds;
  }
  return out;
}

const BuyerAssessment = () => {
  const navigate = useNavigate();
  const [currentStep, setCurrentStep] = useState(0);
  const [allStepsFilled, setAllStepsFilled] = useState(false);
  const [formData, setFormData] = useState({ ...BUYER_COTS_INITIAL_STATE });
  const [submitError, setSubmitError] = useState("");
  const [autoGeneratedLoading, setAutoGeneratedLoading] = useState(false);
  const [onboardingFetched, setOnboardingFetched] = useState(false);
  const [riskMitigationMappingIds, setRiskMitigationMappingIds] = useState<number[]>([]);
  const autoGeneratedFetchedRef = useRef(false);

  const handleContinue = () => setCurrentStep((prev) => prev + 1);
  const handleBack = () => setCurrentStep((prev) => prev - 1);
  const handleBackToAssessments = () => navigate("/assessments");

  // When assessment completes: show "You're all set!" then navigate to assessments page after 2 seconds
  useEffect(() => {
    if (!allStepsFilled) return;
    const t = setTimeout(() => navigate("/assessments"), 2000);
    return () => clearTimeout(t);
  }, [allStepsFilled, navigate]);

  // Fetch buyer onboarding for the current user's org and pre-fill auto-populated fields (read-only in UI)
  useEffect(() => {
    if (onboardingFetched) return;
    const token = sessionStorage.getItem("bearerToken");
    if (!token) return;

    setOnboardingFetched(true);

    const headers = {
      "Content-Type": "application/json",
      Authorization: `Bearer ${token}`,
    };

    const applyBuyerData = (result) => {
      const buyer = result?.data?.buyer ?? null;
      if (buyer && result?.data?.organizationId) {
        sessionStorage.setItem("organizationId", result.data.organizationId);
      }
      const patch = mapOnboardingToAssessmentForm(buyer);
      if (Object.keys(patch).length) {
        setFormData((prev) => ({ ...prev, ...patch }));
      }
    };

    // 1) GET /buyerOnboarding/me – uses JWT to get user's org and return buyer onboarding
    fetch(`${BASE_URL}/buyerOnboarding/me`, { method: "GET", headers })
      .then((res) => res.json())
      .then((result) => {
        if (result?.data != null) {
          applyBuyerData(result);
          return;
        }
        throw new Error("No data");
      })
      .catch(() => {
        const organizationId = sessionStorage.getItem("organizationId");
        if (!organizationId) return;
        return fetch(`${BASE_URL}/orgOnboarding/${encodeURIComponent(organizationId)}`, {
          method: "GET",
          headers,
        })
          .then((res) => res.json())
          .then(applyBuyerData);
      })
      .catch(() => setOnboardingFetched(false));
  }, [onboardingFetched]);

  // Auto Generated step: fetch risk/compute data (not from onboarding)
  useEffect(() => {
    if (currentStep !== 8 || autoGeneratedFetchedRef.current) return;
    const token = sessionStorage.getItem("bearerToken");
    const organizationId = sessionStorage.getItem("organizationId");
    if (!token || !organizationId) return;

    autoGeneratedFetchedRef.current = true;
    setAutoGeneratedLoading(true);
    fetch(`${BASE_URL}/buyerCotsAssessment/autoGenerated`, {
      method: "POST",
      headers: {
        "Content-Type": "application/json",
        Authorization: `Bearer ${token}`,
      },
      body: JSON.stringify({ organizationId, ...formData }),
    })
      .then((res) => res.json())
      .then((result) => {
        if (result.data) {
          setFormData((prev) => {
            const next = { ...prev };
            AUTO_GENERATED_KEYS.forEach((key) => {
              if (result.data[key] != null) next[key] = String(result.data[key]);
            });
            return next;
          });
          const ids = result.data.riskMitigationMappingIds;
          if (Array.isArray(ids)) {
            setRiskMitigationMappingIds(ids.map((id) => Number(id)).filter((n) => !Number.isNaN(n)));
          }
        }
      })
      .catch(() => {
        autoGeneratedFetchedRef.current = false;
      })
      .finally(() => setAutoGeneratedLoading(false));
  }, [currentStep]);

  const handleSubmit = async (e) => {
    e.preventDefault();
    setSubmitError("");
    const token = sessionStorage.getItem("bearerToken");
    const organizationId = sessionStorage.getItem("organizationId");
    if (!organizationId) {
      setSubmitError("Organization context missing. Please complete onboarding or log in again.");
      return;
    }
    try {
      const response = await fetch(`${BASE_URL}/buyerCotsAssessment`, {
        method: "POST",
        headers: {
          "Content-Type": "application/json",
          Authorization: `Bearer ${token}`,
        },
        body: JSON.stringify({
          organizationId,
          ...prepareSubmitPayload(formData, riskMitigationMappingIds),
        }),
      });
      const result = await response.json();
      if (!response.ok) {
        throw new Error(result.message || "Failed to submit assessment");
      }
      setAllStepsFilled(true);
    } catch (err) {
      setSubmitError(err.message || "Failed to submit assessment");
    }
  };

  return (
    <>
      <CardContainerOnBoarding>
        <form onSubmit={handleSubmit}>
          <CardOnBoarding className="card_vendor">
            {currentStep === 0 && (
              <OrganizationProfile
                data={BUYER_COTS_ASSESSMENT.organizationProfile}
                formData={formData}
                setFormData={setFormData}
                readOnlyKeys={BUYER_COTS_READONLY_KEYS}
              />
            )}
            {currentStep === 1 && (
              <UseCase
                data={BUYER_COTS_ASSESSMENT.useCase}
                formData={formData}
                setFormData={setFormData}
                readOnlyKeys={BUYER_COTS_READONLY_KEYS}
              />
            )}
            {currentStep === 2 && (
              <VendorEvaluation
                data={BUYER_COTS_ASSESSMENT.vendorEvaluation}
                formData={formData}
                setFormData={setFormData}
                readOnlyKeys={BUYER_COTS_READONLY_KEYS}
              />
            )}
            {currentStep === 3 && (
              <Readiness
                data={BUYER_COTS_ASSESSMENT.readiness}
                formData={formData}
                setFormData={setFormData}
                readOnlyKeys={BUYER_COTS_READONLY_KEYS}
              />
            )}
            {currentStep === 4 && (
              <RiskProfile
                data={BUYER_COTS_ASSESSMENT.riskProfile}
                formData={formData}
                setFormData={setFormData}
                readOnlyKeys={BUYER_COTS_READONLY_KEYS}
              />
            )}
            {currentStep === 5 && (
              <VendoeRisk
                data={BUYER_COTS_ASSESSMENT.vendorRisk}
                formData={formData}
                setFormData={setFormData}
              />
            )}
            {currentStep === 6 && (
              <Implementation
                data={BUYER_COTS_ASSESSMENT.implementation}
                formData={formData}
                setFormData={setFormData}
              />
            )}
            {currentStep === 7 && (
              <Evidence
                data={BUYER_COTS_ASSESSMENT.evidence}
                formData={formData}
                setFormData={setFormData}
              />
            )}
            {currentStep === 8 && (
              <AutoGenerated
                data={BUYER_COTS_ASSESSMENT.autoGenerated}
                formData={formData}
                readOnly
                loading={autoGeneratedLoading}
              />
            )}
            {currentStep === 9 && !allStepsFilled && (
              <StepBuyerCotsPreview formData={formData} />
            )}
            {currentStep === 9 && allStepsFilled && <CardConfirmation />}
          </CardOnBoarding>

          {submitError && (
            <p className="form-error" style={{ color: "red", margin: "8px 0" }}>
              {submitError}
            </p>
          )}

          <div className="vendor_action_btns">
            {!allStepsFilled && (
              <div className="action_back">
                <Button
                  type="button"
                  onClick={currentStep === 0 ? handleBackToAssessments : handleBack}
                  className="back_btn"
                >
                  <span>
                    <ChevronLeftCircle size={16} />
                    Back
                  </span>
                </Button>
              </div>
            )}

            {currentStep < 9 && !allStepsFilled && (
              <div className="action_continue_btn">
                <Button
                  type="button"
                  onClick={handleContinue}
                  className="continue_btn"
                >
                  <span>
                    Continue <ChevronRightCircle size={16} />
                  </span>
                </Button>
              </div>
            )}

            {currentStep === 9 && !allStepsFilled && (
              <div className="action_submit_btn">
                <Button type="submit" className="submit_btn_vendor">
                  <span>
                    Submit <Send size={16} />
                  </span>
                </Button>
              </div>
            )}
          </div>
        </form>
      </CardContainerOnBoarding>
    </>
  );
};

export default BuyerAssessment;
